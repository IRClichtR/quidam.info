// @ts-check
// Dev script: prints public/js/tz-countries.js, the countries of each time zone, from IANA zone1970.tab.
// Run with `node scripts/gen-tz-countries.js > public/js/tz-countries.js` and commit the output.

const SOURCE = 'https://data.iana.org/time-zones/data/zone1970.tab';

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);

/** @type {[string, string[]][]} */
const rows = [];
for (const line of (await res.text()).split('\n')) {
  if (!line || line.startsWith('#')) continue;
  // Columns: country codes (comma-separated), coordinates, zone name, comment.
  const [codes, , zone] = line.split('\t');
  if (!zone || !/^[A-Z]{2}(,[A-Z]{2})*$/.test(codes)) throw new Error(`unexpected line: ${line}`);
  rows.push([zone, codes.split(',')]);
}
rows.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const body = rows.map(([zone, codes]) => `  '${zone}': [${codes.map((c) => `'${c}'`).join(', ')}],`).join('\n');
process.stdout.write(`// @ts-check
// Generated by scripts/gen-tz-countries.js from ${SOURCE}. Do not edit.
// Each time zone with the countries that use it.

/** @type {Record<string, string[]>} */
export default {
${body}
};
`);
