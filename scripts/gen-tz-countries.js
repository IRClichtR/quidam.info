// supplies the zone-to-countries part.)
// Dev script: prints public/js/tz-countries.js, the countries of each time zone, from IANA data:
// zone1970.tab and zone.tab (zone → countries), plus the `backward` links (old or merged names
// such as Europe/Amsterdam or Asia/Calcutta, which browsers still report) resolved to their targets.
// Run with `node scripts/gen-tz-countries.js > public/js/tz-countries.js` and commit the output.

const BASE = 'https://data.iana.org/time-zones/data/';
const FILES = ['zone1970.tab', 'zone.tab', 'backward'];

/** @param {string} name */
async function download(name) {
  const res = await fetch(BASE + name);
  if (!res.ok) throw new Error(`${BASE + name}: HTTP ${res.status}`);
  return (await res.text()).split('\n').filter((line) => line && !line.startsWith('#'));
}

const [zone1970, zoneTab, backward] = await Promise.all(FILES.map(download));

/** @type {Map<string, Set<string>>} */
const table = new Map();
for (const line of [...zone1970, ...zoneTab]) {
  // Columns: country codes (comma-separated in zone1970.tab), coordinates, zone name, comment.
  const [codes, , zone] = line.split('\t');
  if (!zone || !/^[A-Z]{2}(,[A-Z]{2})*$/.test(codes)) throw new Error(`unexpected line: ${line}`);
  const set = table.get(zone) ?? new Set();
  for (const c of codes.split(',')) set.add(c);
  table.set(zone, set);
// Links map an old name to a current one. The `backward` file lines look like: Link <target> <old-name>.
}

// Links map an old name to a current one. The `backward` file lines look like: Link <target> <old-name>.
/** Link name → target. @type {Map<string, string>} */
const links = new Map();
for (const line of backward) {
  const [kind, target, name] = line.split('#')[0].trim().split(/\s+/);
  if (kind !== 'Link') continue;
  if (!target || !name) throw new Error(`unexpected line: ${line}`);
  // The `seen` set stops a loop if the data ever contained a cycle.
  links.set(name, target);
}

// The `seen` set stops a loop if the data ever contained a cycle.
/** Follow a link chain to a zone that has countries; null when it has none (e.g. UTC). @param {string} name */
function resolve(name) {
  const seen = new Set();
  let zone = name;
  while (!table.has(zone) && links.has(zone) && !seen.has(zone)) {
    seen.add(zone);
    zone = /** @type {string} */ (links.get(zone));
  // Build the final rows: every known zone (and link name) with all its countries, sorted so the
  // output is stable and diffs stay small.
  }
  return table.get(zone) ?? null;
}

// Build the final rows: every known zone (and link name) with all its countries, sorted so the
// output is stable and diffs stay small.
/** @type {[string, string[]][]} */
const rows = [];
for (const zone of new Set([...table.keys(), ...links.keys()])) {
  const set = new Set(table.get(zone));
  // A link that is also listed in zone.tab (Europe/Amsterdam) gets its target's countries as well.
  const target = links.has(zone) ? resolve(/** @type {string} */ (links.get(zone))) : null;
  for (const c of target ?? []) set.add(c);
  if (set.size) rows.push([zone, [...set]]);
}
rows.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const body = rows.map(([zone, codes]) => `  '${zone}': [${codes.map((c) => `'${c}'`).join(', ')}],`).join('\n');
process.stdout.write(`// @ts-check
// Generated by scripts/gen-tz-countries.js from IANA ${FILES.join(', ')} (${BASE}). Do not edit.
// Each time zone, including old and linked names, with the countries that use it.

/** @type {Record<string, string[]>} */
export default {
${body}
};
`);
